"""
utils/pdf_report.py
One small helper that turns (title, subtitle, headers, rows) into a
professionally formatted PDF using reportlab — used by every /reports endpoint
so every exported PDF looks consistent.
"""
import io
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

PRIMARY = colors.HexColor("#2563EB")
SURFACE = colors.HexColor("#F1F5F9")


def build_table_pdf(title: str, subtitle: str, headers: list[str], rows: list[list], landscape_mode: bool = False) -> bytes:
    buf = io.BytesIO()
    page = landscape(A4) if landscape_mode else A4
    doc = SimpleDocTemplate(buf, pagesize=page, topMargin=18 * mm, bottomMargin=15 * mm, leftMargin=15 * mm, rightMargin=15 * mm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("StudentHubTitle", parent=styles["Title"], textColor=PRIMARY, fontSize=18, spaceAfter=2)
    sub_style = ParagraphStyle("StudentHubSubtitle", parent=styles["Normal"], textColor=colors.HexColor("#64748B"), fontSize=10, spaceAfter=14)

    elements = [Paragraph("StudentHub", title_style), Paragraph(f"{title} — {subtitle}", sub_style)]

    if not rows:
        elements.append(Paragraph("No data available for this selection.", styles["Normal"]))
    else:
        table_data = [headers] + [[str(c) if c is not None else "—" for c in row] for row in rows]
        table = Table(table_data, repeatRows=1)
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, SURFACE]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        elements.append(table)

    elements.append(Spacer(1, 10 * mm))
    elements.append(Paragraph("Generated by StudentHub — AI-Powered College Management System.", ParagraphStyle("Footer", parent=styles["Normal"], fontSize=8, textColor=colors.HexColor("#94A3B8"))))
    doc.build(elements)
    return buf.getvalue()
